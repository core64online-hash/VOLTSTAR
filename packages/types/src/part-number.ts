import { z } from 'zod';

/**
 * Крос-номер — головний і, за словами продавців, єдиний спосіб, у який клієнт шукає агрегат:
 * він приходить із номером, знятим зі свого стартера чи генератора, або з каталогу техніки.
 *
 * Один і той самий номер пишуть по-різному: «0 001 368 088», «0-001-368-088», «0001368088»,
 * подеколи з крапками або в нижньому регістрі. Щоб усі ці написання знаходили той самий товар,
 * і в базі, і в запиті зберігаємо ще й нормалізовану форму: верхній регістр, лише латиниця й
 * цифри. Кирилиця в номерах трапляється в пострадянських каталогах — її транслітеруємо, щоб
 * «6582.3708000» і «АТЭ-1» не залежали від розкладки, якою набирає клієнт.
 */

/** Кирилиця в номерах агрегатів: збіг накреслень із латиницею (А, В, Е, К, М, Н, О, Р, С, Т, Х). */
const LOOKALIKE: Record<string, string> = {
  А: 'A',
  В: 'B',
  Е: 'E',
  Ё: 'E',
  К: 'K',
  М: 'M',
  Н: 'H',
  О: 'O',
  Р: 'P',
  С: 'C',
  Т: 'T',
  У: 'Y',
  Х: 'X',
  І: 'I',
  Ї: 'I',
};

/** Номер у пошуковій формі: верхній регістр, лише [A-Z0-9]. */
export function normalizePartNumber(value: string): string {
  let out = '';
  for (const ch of value.toUpperCase()) {
    const mapped = LOOKALIKE[ch] ?? ch;
    if (/[A-Z0-9]/.test(mapped)) out += mapped;
  }
  return out;
}

/**
 * Артикул або крос-номер, як його вводять: роздільники дозволені, але після нормалізації
 * має лишитися щонайменше три знаки — коротший «номер» у пошуку дав би пів каталогу.
 */
export const partNumberField = z
  .string()
  .trim()
  .min(1)
  .max(60)
  .refine((v) => normalizePartNumber(v).length >= 3, {
    message: 'Номер має містити щонайменше три літери або цифри',
  });
